-- Patients and the Actions they record.
--
-- Each table has a bigint surrogate key for joins and a UUID that is the only
-- identifier exposed outside the database. Timestamps are timestamptz: the
-- source's naive timestamps are loaded as UTC (ADR 0001).
--
-- No search indexes yet: they are deferred to the volume work, where query
-- plans decide them. The unique constraints on uuid are what the loader's
-- upsert needs.

create table patient (
    id                bigint generated by default as identity primary key,
    uuid              uuid         not null,
    title             varchar(255),
    given_name        varchar(255) not null,
    family_name       varchar(255) not null,
    gender            varchar(255),
    date_of_birth     date,
    nhs_number        varchar(255),
    hospital_id       varchar(255),
    invited_at        timestamptz  not null,
    registered_at     timestamptz,
    discharged_at     timestamptz,
    -- When the source system created the row: the moment the data was extracted.
    source_created_at timestamptz  not null,
    -- Status is derived, never set: the latest stage reached wins.
    -- Keep in step with uk.bit1.engagement.patient.Status#derive.
    status            varchar(16)  not null generated always as (
        case
            when discharged_at is not null then 'DISCHARGED'
            when registered_at is not null then 'REGISTERED'
            else 'INVITED'
        end
    ) stored,
    constraint patient_uuid_key unique (uuid)
);

create table action (
    id                bigint generated by default as identity primary key,
    uuid              uuid         not null,
    patient_id        bigint       not null references patient (id),
    recorded_at       timestamptz  not null,
    module            varchar(32)  not null,
    topic             varchar(64)  not null,
    action_type       varchar(32)  not null,
    -- When the source system created the row: the moment the data was extracted.
    source_created_at timestamptz  not null,
    constraint action_uuid_key unique (uuid)
);
